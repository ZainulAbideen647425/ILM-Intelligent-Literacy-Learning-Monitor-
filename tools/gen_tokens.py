#!/usr/bin/env python3
"""Generate platform token files from design/tokens.json.

Outputs:
  mobile/lib/core/theme/tokens.g.dart
  backend/dashboard/static/css/tokens.css

Usage:
  python tools/gen_tokens.py          # write files
  python tools/gen_tokens.py --check  # fail if generated files are out of date (CI)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "tokens.json"
DART_OUT = ROOT / "mobile" / "lib" / "core" / "theme" / "tokens.g.dart"
CSS_OUT = ROOT / "backend" / "dashboard" / "static" / "css" / "tokens.css"

HEADER = "GENERATED by tools/gen_tokens.py from design/tokens.json. Do not edit by hand."


def kebab(name: str) -> str:
    return "".join("-" + c.lower() if c.isupper() else c for c in name)


def build_dart(tokens: dict) -> str:
    lines = [
        f"// {HEADER}",
        "",
        "import 'package:flutter/painting.dart';",
        "",
        "/// Colour tokens (Rangeen · Direction B).",
        "abstract final class IlmColors {",
    ]
    for name, spec in tokens["color"].items():
        hex_value = spec["value"].lstrip("#").upper()
        lines.append(f"  /// {spec['use']}")
        lines.append(f"  static const Color {name} = Color(0xFF{hex_value});")
    lines += ["}", "", "/// Font family tokens.", "abstract final class IlmFonts {"]
    for name, spec in tokens["font"].items():
        lines.append(f"  /// {spec['use']}")
        lines.append(f"  static const String {name} = '{spec['value']}';")
    lines += ["}", "", "/// Spacing scale (logical pixels).", "abstract final class IlmSpace {"]
    for name, value in tokens["space"].items():
        lines.append(f"  static const double {name} = {float(value)};")
    lines += ["}", "", "/// Corner radii (logical pixels).", "abstract final class IlmRadius {"]
    for name, value in tokens["radius"].items():
        lines.append(f"  static const double {name} = {float(value)};")
    lines += ["}", "", "/// Size tokens (logical pixels).", "abstract final class IlmSize {"]
    for name, value in tokens["size"].items():
        lines.append(f"  static const double {name} = {float(value)};")
    lines += ["}", ""]
    return "\n".join(lines)


def build_css(tokens: dict) -> str:
    lines = [f"/* {HEADER} */", "", ":root {"]
    for name, spec in tokens["color"].items():
        lines.append(f"  --ilm-color-{kebab(name)}: {spec['value']};")
    fallbacks = {"heading": "system-ui, sans-serif", "body": "system-ui, sans-serif", "urdu": "serif"}
    for name, spec in tokens["font"].items():
        lines.append(f"  --ilm-font-{kebab(name)}: '{spec['value']}', {fallbacks.get(name, 'sans-serif')};")
    for name, value in tokens["space"].items():
        lines.append(f"  --ilm-space-{kebab(name)}: {value}px;")
    for name, value in tokens["radius"].items():
        lines.append(f"  --ilm-radius-{kebab(name)}: {value}px;")
    for name, value in tokens["size"].items():
        lines.append(f"  --ilm-size-{kebab(name)}: {value}px;")
    lines += ["}", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    tokens = json.loads(SRC.read_text(encoding="utf-8"))
    outputs = {DART_OUT: build_dart(tokens), CSS_OUT: build_css(tokens)}
    if "--check" in argv:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        if stale:
            print("Run: python tools/gen_tokens.py")
            return 1
        print("tokens up to date")
        return 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
